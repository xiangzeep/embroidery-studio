def current_language() -> str:
    return _LANGUAGE


def set_language(language: str):
    global _LANGUAGE
    if language in _TRANSLATIONS:
        _LANGUAGE = language


def tr(key: str) -> str:
    return (
        _TRANSLATIONS.get(_LANGUAGE, {}).get(key)
        or _TRANSLATIONS["en_US"].get(key)
        or key
    )
